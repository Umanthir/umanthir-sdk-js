#!/usr/bin/env node
// Syncs the Umanthir API OpenAPI contract and generates the SDK types from it.
//
//   node scripts/contract.mjs sync       download the published contract, then generate
//   node scripts/contract.mjs generate   generate from the committed snapshot in openapi/
//
// The generator (openapi-typescript) lives in tools/contract with its own lockfile,
// because it needs the TypeScript 5 compiler API. Install it with:
//   npm ci --prefix tools/contract --ignore-scripts
import { spawnSync } from "node:child_process";
import { existsSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const SPEC_URL = "https://api.umanthir.com/v2/docs/openapi.en.yaml";
const SPEC_DIR = join(ROOT, "openapi");
const OUT_DIR = join(ROOT, "src", "generated");
const MAX_BYTES = 5 * 1024 * 1024;
const SNAPSHOT_RE = /^umanthir-api\.(\d+\.\d+\.\d+)\.en\.yaml$/;
// Schema names that would shadow built-in globals get a public alias.
const RENAMES = { Error: "ErrorBody" };
const HEADER =
  "// Generated by scripts/contract.mjs from the Umanthir API OpenAPI contract. Do not edit.\n";

function fail(message) {
  console.error(`contract: ${message}`);
  process.exit(1);
}

function specVersion(yaml) {
  const info = /^info:\s*\n((?:[ \t]+.*\n)+)/m.exec(yaml);
  const version = info && /^[ \t]+version:\s*['"]?(\d+\.\d+\.\d+)['"]?\s*$/m.exec(info[1]);
  if (!version) fail("info.version not found in the contract");
  return version[1];
}

function schemaNames(yaml) {
  const block = /^ {2}schemas:\s*\n([\s\S]*)/m.exec(yaml);
  if (!block) fail("components.schemas not found in the contract");
  const names = [];
  for (const line of block[1].split("\n")) {
    if (/^\S/.test(line) || /^ {2}\S/.test(line)) break; // left components.schemas
    const m = /^ {4}([A-Za-z_][A-Za-z0-9_]*):\s*$/.exec(line);
    if (m) names.push(m[1]);
  }
  if (names.length === 0) fail("no schemas found in the contract");
  return names;
}

function snapshotPath() {
  const files = existsSync(SPEC_DIR)
    ? readdirSync(SPEC_DIR).filter((f) => SNAPSHOT_RE.test(f))
    : [];
  if (files.length !== 1) fail(`expected exactly one snapshot in openapi/, found ${files.length}`);
  return join(SPEC_DIR, files[0]);
}

async function sync() {
  const url = new URL(SPEC_URL);
  if (url.protocol !== "https:") fail("the contract URL must use https");
  const res = await fetch(url, { redirect: "error", signal: AbortSignal.timeout(30_000) });
  if (!res.ok) fail(`download failed: HTTP ${res.status}`);
  const type = res.headers.get("content-type") ?? "";
  if (!/yaml/i.test(type)) fail(`unexpected content-type: ${type}`);
  const body = await res.text();
  if (Buffer.byteLength(body) > MAX_BYTES) fail("contract larger than 5 MB");
  const version = specVersion(body);
  for (const f of existsSync(SPEC_DIR) ? readdirSync(SPEC_DIR) : []) {
    if (SNAPSHOT_RE.test(f)) rmSync(join(SPEC_DIR, f));
  }
  writeFileSync(join(SPEC_DIR, `umanthir-api.${version}.en.yaml`), body);
  console.log(`contract: saved snapshot ${version}`);
  generate();
}

function generate() {
  const spec = snapshotPath();
  const yaml = readFileSync(spec, "utf8");
  const version = specVersion(yaml);
  const fileVersion = SNAPSHOT_RE.exec(spec.split(/[\\/]/).pop())[1];
  if (version !== fileVersion) fail(`snapshot file ${fileVersion} has info.version ${version}`);

  const bin = join(
    ROOT,
    "tools",
    "contract",
    "node_modules",
    ".bin",
    process.platform === "win32" ? "openapi-typescript.cmd" : "openapi-typescript",
  );
  if (!existsSync(bin))
    fail("generator not installed: run `npm ci --prefix tools/contract --ignore-scripts`");
  const out = join(OUT_DIR, "openapi.ts");
  const run = spawnSync(bin, [spec, "--output", out, "--alphabetize"], {
    stdio: "inherit",
    shell: process.platform === "win32",
  });
  if (run.status !== 0) fail("openapi-typescript failed");
  writeFileSync(out, HEADER + readFileSync(out, "utf8"));

  const lines = schemaNames(yaml).map((name) => {
    const alias = RENAMES[name] ?? name;
    return `export type ${alias} = components["schemas"]["${name}"];`;
  });
  writeFileSync(
    join(OUT_DIR, "schemas.ts"),
    `${HEADER}import type { components } from "./openapi.js";\n\n${lines.join("\n")}\n`,
  );
  writeFileSync(
    join(OUT_DIR, "contract.ts"),
    `${HEADER}/** Version of the Umanthir API contract the SDK types were generated from. */\nexport const API_CONTRACT_VERSION: string = "${version}";\n`,
  );
  console.log(`contract: generated ${lines.length} types from ${version}`);
}

const command = process.argv[2];
if (command === "sync") await sync();
else if (command === "generate") generate();
else fail("usage: node scripts/contract.mjs <sync|generate>");
